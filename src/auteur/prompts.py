SHOTLIST = """\
Break this treatment into a shot list.

{treatment}

Rules:
- Total duration ≈ {seconds} s (sum of shot durations), {aspect} frame.
- Vary shot sizes and moves; motivate every camera move. Cut on action.
- ids S01, S02, … in order. `characters` uses character ids; `location` uses a
  location id.
- keyframe_prompt: the shot's FIRST FRAME as a still photograph. Include shot
  size, lens, composition, who/what is where, wardrobe, lighting, palette and
  the style bible's texture. Refer to characters by name. No camera motion words.
- motion_prompt: an LTX-2.5 prompt — ONE flowing present-tense paragraph of
  4-7 sentences: start with the main action, then specific movements and
  gestures, appearance details, environment, the camera move (e.g. "The camera
  slowly pushes in"), lighting/colour, and finally the audio: ambience, sound
  effects, music, and any dialogue as `Name says, "..."` with the voice's
  character. Literal and visual, no metaphors, no lists.
- transition: how the shot is entered (cut by default; dissolve/fade sparingly).
"""

